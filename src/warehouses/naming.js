const { HttpError } = require('../middleware/errorHandler');

// Имя ряда или зоны — короткое по существу, а не из вредности.
//
// Оно становится первой частью адреса ячейки: было `1.3.4`, стало `А.3.4`.
// Этот адрес работник читает вслух, диктует по рации и вводит в поиск, поэтому
// «Стеллажи у ворот.3.4» им пользоваться нельзя. Плюс на схеме склада ряд —
// это полоса шириной 36px с промежутком 12px до соседней: подпись моноширинным
// шрифтом 15px занимает ~9px на символ, то есть на пятом символе имена соседних
// рядов начинают наезжать друг на друга.
const MAX_NAME_LENGTH = 4;

// Потолки размеров склада. Раньше их не было вовсе: поле в браузере
// ограничивало ввод десяткой, а сервер принял бы и десять тысяч — и вставил бы
// сто миллионов ячеек одним запросом. Числа взяты с большим запасом к
// реальному складу (паллетные стеллажи высотой 12 м — это 6-7 ярусов, у
// клиента ряд из 50 стеллажей), их задача — поймать опечатку, а не стеснить.
const LIMITS = {
  rows: 60,
  racksPerRow: 200,
  tiersPerRack: 30,
  cellsTotal: 60000,
};

// Возвращает NULL для пустого имени: пусто значит «имени нет, показываем
// номер», и это законное состояние, а не ошибка.
function normalizeName(raw, { what }) {
  if (raw === undefined || raw === null) return null;
  const name = String(raw).trim().replace(/\s+/g, ' ');
  if (name === '') return null;

  if ([...name].length > MAX_NAME_LENGTH) {
    throw new HttpError(400, `Название ${what} — не длиннее ${MAX_NAME_LENGTH} символов, иначе адрес ячейки станет нечитаемым`);
  }
  // Точка разделяет части адреса ячейки (`А.3.4`), поэтому внутри имени её
  // быть не может — иначе адрес перестанет разбираться однозначно.
  if (name.includes('.')) {
    throw new HttpError(400, 'В названии нельзя использовать точку — она разделяет части адреса ячейки');
  }
  return name;
}

module.exports = { MAX_NAME_LENGTH, LIMITS, normalizeName };
