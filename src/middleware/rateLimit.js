// Ограничение частоты для дверей, в которые стучат снаружи.
//
// Вход по паролю и вход по ключу — единственные места, где можно перебирать:
// у одного пароль, у другого короткий код вида `7721-01`. Без счётчика ключ из
// четырёх цифр и двух подбирается за минуты, и никто об этом не узнает.
//
// В памяти процесса, а не в базе. Перезапуск сбрасывает счётчик — это
// приемлемо: задача не остановить упорного злоумышленника (для этого нужен
// внешний заслон), а сделать перебор бессмысленно медленным и оставить след
// в логах.
const buckets = new Map();

// `failuresOnly` — считать только неудачи.
//
// Иначе счётчик наказывает за нормальную работу. Ключи работников считаются
// по адресу, а весь склад сидит за одним: двадцать человек, приходящих в
// смену, вводят ключи в течение пяти минут, и шестнадцатый получает «слишком
// много попыток». То же с обменом 1С — он ходит с того же адреса, что и люди.
// Перебору же удачный ответ не нужен: подобрал — счётчик уже неважен.
function rateLimit({ windowMs, max, key, message, failuresOnly = false }) {
  return (req, res, next) => {
    const id = key(req);
    // Некого считать (нет ни адреса, ни поля) — пропускаем: лучше пустить,
    // чем заблокировать всех под одним пустым ключом.
    if (!id) return next();

    const now = Date.now();
    const hits = (buckets.get(id) || []).filter((t) => now - t < windowMs);
    if (hits.length >= max) {
      const waitSec = Math.ceil((windowMs - (now - hits[0])) / 1000);
      res.set('Retry-After', String(waitSec));
      return res.status(429).json({ error: message || `Слишком много попыток. Подождите ${waitSec} с.` });
    }
    hits.push(now);
    buckets.set(id, hits);

    if (failuresOnly) {
      // Попытку записали заранее — иначе пачка одновременных запросов
      // проскочит мимо счётчика, пока ни один из них не ответил. Удачный
      // ответ её возвращает.
      res.on('finish', () => {
        if (res.statusCode >= 400) return;
        const left = (buckets.get(id) || []).filter((t) => t !== now);
        if (left.length === 0) buckets.delete(id);
        else buckets.set(id, left);
      });
    }

    // Карта не должна расти бесконечно: изредка выметаем остывшее.
    if (buckets.size > 1000) {
      for (const [k, times] of buckets) {
        if (times.every((t) => now - t >= windowMs)) buckets.delete(k);
      }
    }
    return next();
  };
}

const ipOf = (req) => req.ip || req.socket?.remoteAddress || null;

// Вход по паролю: считаем и по адресу, и по самой почте. Только по адресу —
// и перебор с сотни адресов проходит мимо; только по почте — и один сломанный
// клиент блокирует чужой аккаунт.
const loginLimiter = rateLimit({
  windowMs: 15 * 60 * 1000,
  max: 10,
  key: (req) => {
    const ip = ipOf(req);
    const login = String(req.body?.email || req.body?.keyCode || '').trim().toLowerCase();
    return ip ? `${ip}|${login}` : null;
  },
  message: 'Слишком много попыток входа. Подождите несколько минут.',
  failuresOnly: true,
});

// Вход по ключу — то же самое, но ключи короткие, поэтому окно жёстче.
const keyLoginLimiter = rateLimit({
  windowMs: 10 * 60 * 1000,
  max: 15,
  key: ipOf,
  message: 'Слишком много попыток входа по ключу. Подождите несколько минут.',
  failuresOnly: true,
});

// Регистрация. Дверь открыта настежь и должна быть открыта — но не для
// заведения складов пачками: почта не подтверждается, и каждый такой склад
// это ещё и доступ к платным ручкам ниже.
const registerLimiter = rateLimit({
  windowMs: 60 * 60 * 1000,
  max: 5,
  key: ipOf,
  message: 'Слишком много регистраций с одного адреса. Попробуйте позже.',
});

// Вопрос агенту стоит денег — и не тех, что платит спрашивающий.
//
// Ключ языковой модели наш, счёт наш, а зарегистрироваться может кто угодно
// за минуту. Без счётчика любой желающий превращает Аргус в бесплатный доступ
// к модели за наши деньги. Тридцать вопросов в час — заметно больше, чем
// нужно человеку, разбирающему склад, и заметно меньше, чем нужно, чтобы
// это стало кому-то интересно.
const agentLimiter = rateLimit({
  windowMs: 60 * 60 * 1000,
  max: 30,
  // По складу, а не по адресу: у склада один владелец и несколько устройств,
  // а тратит он одну общую квоту.
  key: (req) => req.auth?.warehouseId || ipOf(req),
  message: 'Слишком много вопросов агентам за час. Подождите — счёт за модель общий.',
});

module.exports = {
  rateLimit, loginLimiter, keyLoginLimiter, registerLimiter, agentLimiter,
};
