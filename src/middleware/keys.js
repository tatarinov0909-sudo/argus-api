const crypto = require('crypto');

// Случайная часть ключа доступа.
//
// Ключи сотрудников выдавались подряд: `7721-01`, `7721-02`, `7721-03`.
// Код склада написан в кабинете крупными цифрами, его знает каждый работник и
// видит каждый, кому показали экран. Значит, чтобы войти чужим ключом, хватало
// перебрать два знака — двадцать попыток на склад из двадцати человек. Считать
// это ключом нельзя: это табличка с номером кабинета.
//
// Ключ продавца был не лучше: четыре случайные цифры (девять тысяч вариантов)
// от Math.random, который для секретов не предназначен вовсе.
//
// Здесь единственный источник случайности для всех ключей: crypto, и алфавит
// без похожих знаков — ключ диктуют по телефону и вводят с бумажки, поэтому
// ноль и буква O, единица и I в нём не встречаются.
const ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'; // 32 знака, без 0 O 1 I

function randomPart(length = 4) {
  // rejection-free: 256 делится на 32, поэтому байты можно брать по модулю
  // без перекоса вероятностей.
  const bytes = crypto.randomBytes(length);
  let out = '';
  for (let i = 0; i < length; i += 1) out += ALPHABET[bytes[i] % ALPHABET.length];
  return out;
}

module.exports = { randomPart, ALPHABET };
