const { HttpError } = require('./errorHandler');

// Проверка количества на входе.
//
// Столбцы `declared_qty`, `accepted_qty` и `cell_stock.qty` — самые старые
// в схеме, и единственные без ограничения в базе: у возвратов, резервов,
// наборов и перемещений `CHECK (qty > 0)` есть, а здесь его не было. Проверка
// в маршрутах тоже сводилась к «не null».
//
// Значит принималось и минус пятьсот. Приёмка с отрицательным числом не
// «ничего не приняли», а списание чужого товара с полки: остаток в ячейке
// уменьшается, и никакой ошибки при этом не возникает — расхождение просто
// уезжает продавцу как факт. Ноль в накладной так же тих: позиция есть,
// собирать нечего, а в сумме «штук» её не видно.
//
// Одна функция на все входы, потому что второе такое место обязательно
// напишут иначе.
// Больше десяти миллионов штук в одной строке не бывает: это столбец
// штрихкода, выбранный в Excel вместо количества (проверка 07.10, Н8). Та же
// граница, что у привоза продавца файлом.
const MAX_QTY = 10000000;

function requireQty(value, label, { min = 0 } = {}) {
  const n = Number(value);
  if (value === null || value === undefined || value === '' || typeof value === 'boolean' || !Number.isFinite(n)) {
    throw new HttpError(400, `${label}: нужно число`);
  }
  if (n > MAX_QTY) {
    throw new HttpError(400, `${label}: больше ${MAX_QTY.toLocaleString('ru-RU')} шт. — проверьте число`);
  }
  if (n < min) {
    throw new HttpError(400, `${label}: не может быть меньше ${min}`);
  }
  if (min > 0 && n === 0) {
    throw new HttpError(400, `${label}: не может быть нулём`);
  }
  // Дробное количество на складе штучного товара — почти всегда опечатка
  // в лишнюю точку, а не полторы коробки. Весовой товар появится — появится
  // и признак у номенклатуры; пока честнее отказать, чем принять 1.5 штуки
  // и сложить их с целыми в отчёте.
  if (!Number.isInteger(n)) {
    throw new HttpError(400, `${label}: должно быть целым`);
  }
  return n;
}

module.exports = { requireQty, MAX_QTY };
