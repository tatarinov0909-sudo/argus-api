// Разбор ведомости 1С «Ведомость по товарам на складах»: одна и та же
// логика для отчёта «Артикул → Код → Номенклатура» и для отчёта по дням
// «Артикул → Наименование» с группой склада сверху.
const test = require('node:test');
const assert = require('node:assert');
const { parseStockSheet } = require('../src/cells/stockAlign');

test('три уровня: артикул, код, номенклатура; «…, шт» срезается', () => {
  const grid = [
    [null, 'Ведомость по товарам на складах'],
    [null, 'Номенклатура.Артикул ', 'Количество (в базовых единицах)'],
    [null, 'Номенклатура.Код', 'Приход', 'Расход', 'Конечный остаток'],
    [null, 'Номенклатура, Базовая единица измерения'],
    [],
    [null, 1201001106, null, null, 28],
    [null, 'PB000021307', null, null, 28],
    [null, 'Печенье с мятой 96г, шт', null, null, 28],
    [],
    // Соседний товар с теми же числами — это другой товар, а не продолжение.
    [null, 1201001107, null, null, 28],
    [null, 'PB000021308', null, null, 28],
    [null, 'Печенье с клубникой 96г, шт', null, null, 28],
    [null, 'Итог', 0, 0, 56],
  ];
  const r = parseStockSheet(grid);
  assert.equal(r.length, 2);
  assert.deepEqual(r[0], { article: '1201001106', code: 'PB000021307', name: 'Печенье с мятой 96г', qty: 28, barcode: null });
  assert.equal(r[1].code, 'PB000021308');
});

test('отчёт по дням: берётся последний «Конечный остаток», строка склада пропускается', () => {
  const grid = [
    [null, 'Ведомость по товарам на складах'],
    [null, 'Склад', '21.07.2026', null, null, 'Итог'],
    [null, 'Номенклатура.Артикул ', 'Количество', null, null, 'Количество'],
    [null, 'Номенклатура.Наименование', 'Приход', 'Расход', 'Конечный остаток', 'Конечный остаток'],
    [null, 'ОТВЕТСТВЕННОЕ ХРАНЕНИЕ', 10, 0, 10, 15],
    [null, 'purplehipbands', 10, 0, 10, 12],
    [null, 'Набор резинок фиолетовый (70 шт. в коробке)  2043570160956', 10, 0, 10, 12],
    [null, 'bluemat', null, null, null, 3],
    [null, 'Коврик синий 2049387910197', null, null, null, 3],
    [null, null, 10, 0, 10, 15],
  ];
  const r = parseStockSheet(grid);
  assert.equal(r.length, 2);
  assert.deepEqual(r[0], { article: 'purplehipbands', code: null,
    name: 'Набор резинок фиолетовый (70 шт. в коробке)  2043570160956', qty: 12, barcode: '2043570160956' });
  assert.equal(r[1].qty, 3);
});

test('не ведомость — понятный отказ', () => {
  assert.throws(() => parseStockSheet([['Товар', 'Кол-во'], ['А', 1]]), /Конечный остаток/);
});
